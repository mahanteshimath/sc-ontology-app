GRANT USAGE ON SCHEMA SUPPLY_CHAIN.SEMANTIC TO ROLE SC_ONTOLOGY_STEWARD;

GRANT USAGE ON SCHEMA SUPPLY_CHAIN.GOVERNANCE TO ROLE SC_PLANNER;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.GOVERNANCE TO ROLE SC_PROCUREMENT;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.GOVERNANCE TO ROLE SC_LOGISTICS;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.GOVERNANCE TO ROLE SC_LOGISTICS_EU;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.GOVERNANCE TO ROLE SC_ONTOLOGY_STEWARD;

GRANT USAGE ON SCHEMA SUPPLY_CHAIN.CANONICAL TO ROLE SC_PLANNER;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.CANONICAL TO ROLE SC_PROCUREMENT;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN.CANONICAL TO ROLE SC_LOGISTICS;
